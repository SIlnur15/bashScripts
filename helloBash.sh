#!/bin/bash

value=$(cat << 'EOF'
/\_/\    (hello, bash!)
>^,^< __/
 / \
(|_|)_/
EOF
)

echo "$value"

# explaination (после этого блока объяснение разницы между < и <<):

# 1. Внешняя часть: value=$( ... ) — Подстановка команды. value= — это создание обычной переменной с именем value. $( ... ) — это синтаксис подстановки команды
# (command substitution). Bash сначала выполняет то, что написано внутри скобок, забирает весь текстовый вывод этой команды и записывает его в переменную value.

# 2. Внутренняя часть: cat << 'EOF' ... EOF — Конструкция Here-DocКонструкция << называется Here-Document («текст прямо здесь»). Она используется для передачи
# многострочного текста в команду (в данном случае в команду cat). cat — это стандартная утилита, которая просто выводит на экран то, что ей передали.<< 'EOF'
# — это указатель для Bash: «Всё, что пойдет со следующей строки и до слова EOF, нужно передать в команду cat». Слово EOF означает End of File (конец файла),
# но вместо него можно написать любое слово, например KOTIK или STOP.Важная деталь — Одинарные кавычки 'EOF': Они отключают интерпретацию спецсимволов внутри
# текста. Без кавычек Bash подумал бы, что косая черта \ — это попытка экранирования, и рисунок бы сломался (пропали бы некоторые линии). Кавычки говорят:
# «Воспринимай этот текст буквально, как он написан». (я это понял типа как сырая строка в python) EOF в самом конце — сигнализирует о том, что многострочный
# текст закончился.В итоге вся эта конструкция внутри скобок просто выдает чистый текст с котиком, который благодаря $( ... ) сохраняется в переменную.

# 3. Вывод на экран: echo "$value". echo — команда, которая выводит текст в терминал. Двойные кавычки "$value" — это критически важный момент в Bash. Если убрать
# кавычки и написать просто echo $value, то Bash сожмет все пробелы и переносы строк в одну строчку, и котик превратится в кашу:
# /\_/\ (hello, bash!) >^,^< __/ / \ (|_|)_/. Кавычки заставляют Bash сохранить структуру текста, включая все отступы и переводы строк.

# explaination between < and <<:
# Разница заключается в том, откуда именно команда получает данные: из готового файла или из текста внутри самого скрипта. В терминах Bash оба символа выполняют
# перенаправление ввода, но работают совершенно по-разному.
# 1. Одинарный знак < (Перенаправление из файла) Этот знак говорит команде: «Возьми данные из существующего файла и прочитай их». Синтаксис: команда < имя_файла
# Пример: cat < MyFile.txt. Здесь команда cat откроет файл MyFile.txt на жестком диске и выведет его содержимое.
# 2. Двойной знак << (Here-Document / Текст «прямо здесь») Этот знак говорит команде: «Не ищи файлы на диске. Данные пойдут прямо со следующей строчки скрипта.
# Читай их, пока не встретишь стоп-слово». Синтаксис: команда << СТОП_СЛОВО Пример: cat << 'EOF'
# Привет, это первая строка.
# А это вторая строка.
# EOF
# Здесь нет никаких внешних файлов. Весь текст написан прямо внутри вашего Bash-скрипта, и cat прочитает его на лету.
# Главное отличие одной фразой: < нужен для работы с внешними файлами. << нужен для вставки многострочного текста прямо в тело скрипта.
# не стоит их путать с операторами > и >>, отвечающими за ВЫВОД (а не ввод как < и <<) данных:
# 1. Одинарный знак > (Запись с нуля / Перезапись)Этот знак берет результат работы команды и записывает его в файл. Если файл уже существовал, всё его старое
# содержимое удаляется, а новый текст пишется поверх.
# 2. Двойной знак >> (Дозапись в конец файла) Этот знак не трогает старые данные. Он открывает файл, перемещает указатель в самый конец и дописывает туда новые строки.
