#!/usr/bin/bash

# the first simple example
result=$(find /home/mars/bashScripts/littleLessons -type f -name "*fufile*") # $(...) механизм подставновки команд
echo $? # стандартный способ вывести код ошибки, 0-ошибок нет

if [ $? -ne 0 ] # проверка, что ошибка не равна 0, между [ и ] обязательны пробелы
then
echo "the file exists"
else
echo "there is no a positive result"
fi
# Но вывод будет нелогичным и дело вот в чем: тут появляется ловушка - $? затирается каждой командой:
# $? — это код завершения последней выполненной команды. Смотри, что происходит по шагам:
# result=$(find ...) — в $? попадает код выхода find (скажем, 0).
# echo $? — ты его выводишь (видишь 0), но сам echo отрабатывает успешно и перезаписывает $? на свой собственный код — тоже 0.
# поэтому, когда в дальнейшем коде - if [ $? -ne 0 ] — здесь $? — это уже код echo, а не find. Он равен 0, значит условие -ne 0 ложно, и ты всегда попадёшь в else.
# То есть проверка проверяет не то, что ты хотел: она смотрит на echo, а не на find. Поэтому я и получаю казалось бы нелогичный вывод

# find - поиск файлов, grep - поиск текста в файле
# -type f - поиск обычных файлов (не путей), т. к. в Linux все файлы
# -name - поиск строго по имени, предполагает точное сопоставление, но регулярки делают подход гибче
# * - в регулярках, любое количество символов
# -ne - Not Equal, будет отдельная тема сравнения чисел
# "$?" - код ошибки

# elif (напомнило python)
if pwd
then
echo "1"
elif pwd
then
echo "2"
fi
